from svg_processor.gcode_gen import generate_gcode
from svg_processor.parser import parse_svg
from svg_processor.transform import fit_to_work_area


def test_parse_svg_line():
    svg = b'<svg><path d="M0 0 L10 0 L10 10" /></svg>'
    paths = parse_svg(svg)
    assert len(paths) >= 1
    assert paths[0][0] == (0.0, 0.0)


def test_fit_to_work_area_scales_points():
    polylines = [[(0, 0), (10, 10)]]
    scaled = fit_to_work_area(polylines, 200, 200)
    assert len(scaled) == 1
    assert scaled[0][0][0] > 0
    assert scaled[0][1][1] > 0


def test_generate_gcode_starts_and_ends_properly():
    lines = generate_gcode([[(0, 0), (10, 10)]], laser_duty=512)
    assert lines[0] == '; Generated by laser-engraver-server'
    assert lines[1] == 'G28'
    assert any(line.startswith('M3 S512') for line in lines)
    assert lines[-2] == 'G28'
