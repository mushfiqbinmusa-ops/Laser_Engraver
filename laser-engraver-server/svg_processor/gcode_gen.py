from __future__ import annotations

from typing import List, Tuple

Polyline = List[Tuple[float, float]]


def generate_gcode(
    polylines: List[Polyline],
    laser_duty: int = 1024,
    travel_speed: int = 500,
    engrave_speed: int = 200,
    comment_header: str = "",
) -> List[str]:
    lines: List[str] = []
    if comment_header:
        lines.append(f"; {comment_header}")

    lines.append("; Generated by laser-engraver-server")
    lines.append("G28")
    lines.append("M5")
    lines.append(f"M220 S{engrave_speed}")

    for path_index, polyline in enumerate(polylines):
        if not polyline:
            continue
        lines.append(f"; Path {path_index + 1}/{len(polylines)}")
        x0, y0 = polyline[0]
        lines.append(f"G0 X{int(round(x0))} Y{int(round(y0))}")
        lines.append(f"M3 S{int(laser_duty)}")
        for x, y in polyline[1:]:
            lines.append(f"G1 X{int(round(x))} Y{int(round(y))}")
        lines.append("M5")

    lines.append("G28")
    lines.append("; Job complete")
    return lines
